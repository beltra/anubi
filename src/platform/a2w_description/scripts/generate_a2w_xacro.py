#!/usr/bin/env python3
"""Generate urdf/a2w_body.urdf.xacro from the upstream Unitree A2 URDF.

Upstream: unitree_ros robots/a2_description/urdf/a2.urdf (BSD-3-Clause), vendored
as urdf/a2_upstream.urdf. The A2-W wheeled variant has no public model, so this
derives it from the legged A2:
  - mesh paths rewritten to package://a2w_description/meshes/
  - the point-foot links (Link4 meshes) are replaced by wheels at the calf tip
    (continuous *_foot_joint about +y, the Go2-W / B2-W convention)
  - every leg joint type and its zero-pose offset are xacro expressions, so the
    same file serves the real robot (revolute, driven by /joint_states) and the
    sim (fixed in the standing pose, lumped into base_link by URDF->SDF)
  - upstream lidar/camera frames are dropped; a2w.urdf.xacro re-adds them

Re-run after updating a2_upstream.urdf:
  python3 scripts/generate_a2w_xacro.py
"""

import os
import xml.etree.ElementTree as ET

PKG_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(PKG_DIR, "urdf", "a2_upstream.urdf")
DST = os.path.join(PKG_DIR, "urdf", "a2w_body.urdf.xacro")

LEGS = ("FL", "FR", "RL", "RR")
DROP_LINKS = {"camera_link", "front_lidar_link", "rear_lidar_link"}


def main():
    root = ET.parse(SRC).getroot()
    out = ET.Element("robot", {"xmlns:xacro": "http://www.ros.org/wiki/xacro"})
    for elem in root:
        if elem.tag == "link":
            name = elem.get("name")
            if name in DROP_LINKS or name.endswith("_foot"):
                continue
            for mesh in elem.iter("mesh"):
                fname = os.path.basename(mesh.get("filename"))
                mesh.set("filename", "package://a2w_description/meshes/" + fname)
            out.append(elem)
        elif elem.tag == "joint":
            name = elem.get("name")
            child = elem.find("child").get("link")
            if child in DROP_LINKS or name.endswith("_foot_joint"):
                continue
            leg, part = name.split("_")[0], name.split("_")[1]
            if leg in LEGS and part in ("hip", "thigh", "calf"):
                elem.set("type", "${leg_joint_type}")
                origin = elem.find("origin")
                q = "${%s_q_%s}" % (leg, part)
                # hip axis is +x, thigh/calf axes are +y in the upstream model.
                if part == "hip":
                    origin.set("rpy", "%s 0 0" % q)
                else:
                    origin.set("rpy", "0 %s 0" % q)
            out.append(elem)

    ET.indent(out, space="  ")
    body = ET.tostring(out, encoding="unicode")
    header = (
        '<?xml version="1.0"?>\n'
        "<!-- GENERATED by scripts/generate_a2w_xacro.py from a2_upstream.urdf\n"
        "     (unitree_ros, BSD-3-Clause). Do not edit by hand.\n"
        "     Requires properties: leg_joint_type and <LEG>_q_<hip|thigh|calf>\n"
        "     (set by a2w.urdf.xacro). -->\n"
    )
    # Drop the outer <robot> wrapper: this file is included into a2w.urdf.xacro.
    body = body.replace(
        '<robot xmlns:xacro="http://www.ros.org/wiki/xacro">',
        '<robot xmlns:xacro="http://www.ros.org/wiki/xacro" name="a2w_body">', 1)
    with open(DST, "w") as fh:
        fh.write(header + body + "\n")
    print("wrote", DST)


if __name__ == "__main__":
    main()
