#!/usr/bin/env python3
"""Generate urdf/a2w_body.urdf.xacro from the official Unitree A2-W URDF.

Upstream: Unitree "A2W_Description" (X2-0807urdf/a2_wheel.urdf, package licence BSD),
linked from the A2 SDK guide, vendored as urdf/a2w_upstream.urdf with its meshes.
Changes applied here:
  - mesh paths rewritten to package://a2w_description/meshes/
  - world link and floating base joint dropped
  - wheel links: the debug sphere visual is dropped and the mesh collision is
    replaced by a cylinder fitted to the tyre mesh (r 0.0948, width 0.050, centre
    0.0494 m outboard of the calf), which contact solvers handle far better
  - wheel joints become ${wheel_joint_type} (continuous on the real robot / articulated
    sim, fixed in the kinematic sim) without position limits
  - leg joint types and zero-pose offsets become xacro expressions, so the same file
    serves the articulated model and the sim's frozen standing pose
Sensor frames are not in the upstream file; a2w.urdf.xacro adds them from the A2 URDF.

Re-run after updating a2w_upstream.urdf:
  python3 scripts/generate_a2w_xacro.py
"""

import os
import xml.etree.ElementTree as ET

PKG_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(PKG_DIR, "urdf", "a2w_upstream.urdf")
DST = os.path.join(PKG_DIR, "urdf", "a2w_body.urdf.xacro")

LEGS = ("FL", "FR", "RL", "RR")
DROP_LINKS = {"world"}

# Fitted to meshes/*_Link4.STL (tyre bounding box).
WHEEL_RADIUS = 0.0948
WHEEL_WIDTH = 0.050
WHEEL_CENTER_Y = 0.0494


def wheel_collision(side):
    col = ET.Element("collision")
    ET.SubElement(col, "origin", {
        "xyz": "0 %.4f 0" % (side * WHEEL_CENTER_Y),
        "rpy": "1.5708 0 0",
    })
    geom = ET.SubElement(col, "geometry")
    ET.SubElement(geom, "cylinder", {"radius": "%.4f" % WHEEL_RADIUS, "length": "%.3f" % WHEEL_WIDTH})
    return col


def main():
    root = ET.parse(SRC).getroot()
    out = ET.Element("robot", {"xmlns:xacro": "http://www.ros.org/wiki/xacro"})
    for elem in root:
        if elem.tag == "link":
            name = elem.get("name")
            if name in DROP_LINKS:
                continue
            for mesh in elem.iter("mesh"):
                fname = os.path.basename(mesh.get("filename"))
                mesh.set("filename", "package://a2w_description/meshes/" + fname)
            if name.endswith("_wheel"):
                for visual in list(elem.findall("visual")):
                    if visual.find("geometry/sphere") is not None:
                        elem.remove(visual)
                for collision in list(elem.findall("collision")):
                    elem.remove(collision)
                side = 1 if name[1] == "L" else -1
                elem.append(wheel_collision(side))
            out.append(elem)
        elif elem.tag == "joint":
            name = elem.get("name")
            if elem.get("type") == "floating" or elem.find("parent").get("link") in DROP_LINKS:
                continue
            leg, part = name.split("_")[0], name.split("_")[1]
            if leg in LEGS and part in ("hip", "thigh", "calf"):
                elem.set("type", "${leg_joint_type}")
                origin = elem.find("origin")
                q = "${%s_q_%s}" % (leg, part)
                # hip axis is +x, thigh/calf axes are +y in the upstream model.
                if part == "hip":
                    origin.set("rpy", "%s 0 0" % q)
                else:
                    origin.set("rpy", "0 %s 0" % q)
            elif leg in LEGS and part == "wheel":
                elem.set("type", "${wheel_joint_type}")
                limit = elem.find("limit")
                for key in ("lower", "upper"):
                    limit.attrib.pop(key, None)
            out.append(elem)

    ET.indent(out, space="  ")
    body = ET.tostring(out, encoding="unicode")
    header = (
        '<?xml version="1.0"?>\n'
        "<!-- GENERATED by scripts/generate_a2w_xacro.py from a2w_upstream.urdf\n"
        "     (official Unitree A2-W description, BSD). Do not edit by hand.\n"
        "     Requires properties: leg_joint_type, wheel_joint_type and\n"
        "     <LEG>_q_<hip|thigh|calf> (set by a2w.urdf.xacro). -->\n"
    )
    # Drop the outer <robot> wrapper: this file is included into a2w.urdf.xacro.
    body = body.replace(
        '<robot xmlns:xacro="http://www.ros.org/wiki/xacro">',
        '<robot xmlns:xacro="http://www.ros.org/wiki/xacro" name="a2w_body">', 1)
    with open(DST, "w") as fh:
        fh.write(header + body + "\n")
    print("wrote", DST)


if __name__ == "__main__":
    main()
